"""Generate docs/test-results.md from the latest published Allure report (the last CI run on `main`).

Only published data is used: summary, executor and environment widgets plus the per-test `suites.csv`.

Usage (from the repository root): python scripts/generate_test_results.py [report URL]
"""

import csv
import io
import json
import sys
from collections import Counter, defaultdict
from datetime import UTC, datetime
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "test-results.md"
DEFAULT_REPORT_URL = "https://magdau.github.io/eds-python-api-test-automation"
STATUSES = ["passed", "failed", "broken", "skipped"]


def fetch(report_url: str, path: str) -> str:
    with urlopen(f"{report_url}/{path}", timeout=30) as response:  # noqa: S310 - fixed https URL
        return response.read().decode("utf-8")


def environment_value(environment: list[dict], name: str) -> str:
    return next(item["values"][0] for item in environment if item["name"] == name)


def render(report_url: str) -> str:
    summary = json.loads(fetch(report_url, "widgets/summary.json"))
    executor = json.loads(fetch(report_url, "widgets/executors.json"))[0]
    environment = json.loads(fetch(report_url, "widgets/environment.json"))
    tests = list(csv.DictReader(io.StringIO(fetch(report_url, "data/suites.csv"))))

    statistic = summary["statistic"]
    started = datetime.fromtimestamp(summary["time"]["start"] / 1000, UTC)
    stopped = datetime.fromtimestamp(summary["time"]["stop"] / 1000, UTC)
    minutes, seconds = divmod(round(summary["time"]["duration"] / 1000), 60)

    per_module: dict[str, Counter[str]] = defaultdict(Counter)
    milliseconds: Counter[str] = Counter()
    for test in tests:
        per_module[test["SUITE"]][test["STATUS"]] += 1
        milliseconds[test["SUITE"]] += int(test["DURATION IN MS"])
    not_passed = [test for test in tests if test["STATUS"] != "passed"]
    branch = environment_value(environment, "CI.Branch")
    commit = environment_value(environment, "CI.Commit")

    lines = [
        "# Test results",
        "",
        "> Generated by `scripts/generate_test_results.py` from the published Allure report - do not edit by hand.",
        f"> This is a snapshot of one CI run; the always-current results are in the [Allure report]({report_url}/).",
        "",
        "## Run",
        "",
        "| | |",
        "| --- | --- |",
        f"| Build | [{executor['buildName']}]({executor['buildUrl']}) (GitHub Actions) |",
        f"| Branch / commit | `{branch}` / `{commit}` |",
        f"| Scope | {environment_value(environment, 'Test.Scope')} |",
        f"| Started (UTC) | {started:%Y-%m-%d %H:%M:%S} |",
        f"| Finished (UTC) | {stopped:%Y-%m-%d %H:%M:%S} |",
        f"| Duration, first test start to last test stop | {minutes} min {seconds} s |",
        f"| Summed duration of the test bodies | {summary['time']['sumDuration'] / 1000:.1f} s (setup and fixtures excluded) |",
        f"| Python / OS | {environment_value(environment, 'Python')} / {environment_value(environment, 'OS')} |",
        f"| Base URL | {environment_value(environment, 'Base.URL')} |",
        "",
        "## Totals",
        "",
        "| Passed | Failed | Broken | Skipped | Total |",
        "| ---: | ---: | ---: | ---: | ---: |",
        "| " + " | ".join(str(statistic[key]) for key in [*STATUSES, "total"]) + " |",
        "",
        "## Results by module",
        "",
        "| Module | Passed | Failed | Broken | Skipped | Total | Summed time (ms) |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for module in sorted(per_module):
        counts = per_module[module]
        cells = " | ".join(str(counts[status]) for status in STATUSES)
        lines.append(f"| `{module}` | {cells} | {sum(counts.values())} | {milliseconds[module]} |")

    lines += ["", "## Tests that did not pass", ""]
    if not_passed:
        lines += ["| Test | Module | Status |", "| --- | --- | --- |"]
        lines += [f"| `{test['NAME']}` | `{test['SUITE']}` | {test['STATUS']} |" for test in not_passed]
    else:
        lines.append("None - every test passed in this run.")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    url = (sys.argv[1] if len(sys.argv) > 1 else DEFAULT_REPORT_URL).rstrip("/")
    OUTPUT.write_text(render(url), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
